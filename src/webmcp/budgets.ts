export const OUTPUT_BUDGET = 1_500;

/** ชื่อ tool ตามสเปก: 1-128 ตัว · a-z 0-9 `_` `-` `.` เท่านั้น */
export const TOOL_NAME_PATTERN = /^[a-z0-9_.-]{1,128}$/;

/**
 * 🇹🇭 **ประโยคขอบเขตพื้นที่ที่คำอธิบายทุก tool ต้องมี** (มติ D-27 · เจ้าของสั่ง 27 ส.ค. ค่ำ)
 *
 * 🔑 ชั้นนี้ทำงาน **ก่อน** โค้ดเราถูกเรียกด้วยซ้ำ — LLM ฝั่ง agent อ่านแล้วอธิบายให้ผู้ใช้เอง
 *    ว่าทำไมถามเรื่องโตเกียวแล้วไม่ได้คำตอบ ⇒ ประหยัดการเรียกที่ยังไงก็ล้ม 1 รอบเต็ม
 *    ⛔ ห้ามเขียนเป็นข้อจำกัด ("only", "cannot") — เกณฑ์ Impact อ่านว่าเป็น **โฟกัส**
 */
export const THAILAND_SCOPE_PHRASE = 'for locations in Thailand (77 provinces)';

/** วัดความยาวผลลัพธ์แบบเดียวกับที่ฝั่ง agent เห็น (JSON string ไม่จัดรูป) */
export function measureOutput(output: unknown): number {
  try {
    return JSON.stringify(output ?? null).length;
  } catch {
    // อ้างวนหรือค่าที่ serialize ไม่ได้ = บั๊กของ tool เอง ⇒ ให้ตัวเลขที่ทำให้ด่านแดงแน่นอน
    return Number.POSITIVE_INFINITY;
  }
}
